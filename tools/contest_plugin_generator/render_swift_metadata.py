#!/opt/homebrew/bin/python3.14
"""Render non-catalog Swift metadata fixtures from resolved AST facts only."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

RENDERER_VERSION = "1.0.0"


def swift_string(value: str) -> str:
    escaped: list[str] = []
    for character in value:
        codepoint = ord(character)
        if character == '"':
            escaped.append('\\"')
        elif character == "\\":
            escaped.append("\\\\")
        elif character == "\n":
            escaped.append("\\n")
        elif character == "\r":
            escaped.append("\\r")
        elif character == "\t":
            escaped.append("\\t")
        elif codepoint < 0x20 or codepoint == 0x7F:
            escaped.append(f"\\u{{{codepoint:X}}}")
        else:
            escaped.append(character)
    return '"' + "".join(escaped) + '"'


def resolution(field: dict[str, Any], expected: str) -> str:
    if field["status"] == "resolved":
        value = field["value"]
        if expected == "string" and type(value) is str:
            return f".resolved({swift_string(value)})"
        if expected == "integer" and type(value) is int:
            return f".resolved({value})"
        if expected == "string-array" and type(value) is list and all(type(item) is str for item in value):
            return ".resolved([" + ", ".join(swift_string(item) for item in value) + "])"
        return f".unresolved({swift_string(f'resolved value has incompatible type; expected {expected}')})"
    reason = field.get("reason", "value is not statically resolved")
    if type(reason) is not str:
        reason = "unresolved reason has incompatible type"
    return f".unresolved({swift_string(reason)})"


def render(inventory: dict[str, Any]) -> str:
    rows: list[str] = []
    for plugin in inventory["plugins"]:
        declarations = plugin["declarations"]
        rows.append("        .init(\n" +
                    f"            pluginID: {swift_string(plugin['pluginID'])},\n" +
                    f"            sourceSHA256: {swift_string(plugin['source']['sha256'])},\n" +
                    f"            displayName: {resolution(declarations['name'], 'string')},\n" +
                    f"            cabrilloName: {resolution(declarations['cabrillo_name'], 'string')},\n" +
                    f"            mode: {resolution(declarations['mode'], 'string')},\n" +
                    "            supportedBands: .unresolved(\"not declared by the Python plugin\"),\n" +
                    f"            dupeType: {resolution(declarations['dupe_type'], 'integer')},\n" +
                    f"            columns: {resolution(declarations['columns'], 'string-array')},\n" +
                    f"            exchangeHint: {resolution(declarations['EXCHANGE_HINT'], 'string')},\n" +
                    "            scoringPolicy: .unresolved(\"requires shared-policy differential proof\"),\n" +
                    "            multiplierPolicy: .unresolved(\"requires shared-policy differential proof\"),\n" +
                    "            exportPolicy: .unresolved(\"requires shared-policy differential proof\")\n" +
                    "        )")
    return f"""// Generated by render_swift_metadata.py {RENDERER_VERSION}; do not activate directly.
// Source pin: {inventory['upstream']['commit']}
// This fixture contains declared facts only. Unresolved policy is intentionally explicit.

import Foundation

enum GeneratedResolution<Value> {{
    case resolved(Value)
    case unresolved(String)
}}

struct GeneratedContestDefinition {{
    let pluginID: String
    let sourceSHA256: String
    let displayName: GeneratedResolution<String>
    let cabrilloName: GeneratedResolution<String>
    let mode: GeneratedResolution<String>
    let supportedBands: GeneratedResolution<[String]>
    let dupeType: GeneratedResolution<Int>
    let columns: GeneratedResolution<[String]>
    let exchangeHint: GeneratedResolution<String>
    let scoringPolicy: GeneratedResolution<String>
    let multiplierPolicy: GeneratedResolution<String>
    let exportPolicy: GeneratedResolution<String>
}}

enum GeneratedContestDefinitions {{
    static let sourcePin = {swift_string(inventory['upstream']['commit'])}
    static let values: [GeneratedContestDefinition] = [
{',\n'.join(rows)}
    ]
}}
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--inventory", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    inventory = json.loads(args.inventory.read_text(encoding="utf-8"))
    args.output.write_text(render(inventory), encoding="utf-8")


if __name__ == "__main__":
    main()
